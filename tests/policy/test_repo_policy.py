"""Run with: python3 -m unittest discover -s tests/policy -v.

Fixture commits are deliberately unsigned. Tests mock only the structural
signature predicate when testing other commit rules, never cryptographic trust.
"""

import copy
import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location(
    "repo_policy", ROOT / "scripts/repo_policy.py"
)
policy = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(policy)
RULES = policy.load_policy(ROOT)
BODY = "Keep the checked runtime boundary explicit so cancellation remains reliable."
MESSAGE = f"fix(runtime): preserve cancellation ownership\n\n{BODY}\n"


class MessageTests(unittest.TestCase):
    def errors(self, message=MESSAGE, parents=()):
        return policy.message_errors(message, parents, RULES)

    def test_valid_types_and_scopes(self):
        for kind in RULES["commit"]["types"]:
            for scope in RULES["commit"]["scopes"]:
                with self.subTest(kind=kind, scope=scope):
                    self.assertEqual(
                        self.errors(
                            f"{kind}({scope}): preserve checked ownership\n\n{BODY}"
                        ),
                        [],
                    )

    def test_required_scope_and_known_type(self):
        for subject in (
            "fix: preserve ownership",
            "fix(unknown): preserve ownership",
            "unknown(repo): preserve ownership",
        ):
            with self.subTest(subject=subject):
                self.assertTrue(self.errors(subject))

    def test_subject_limits_and_target_warning(self):
        warnings = []
        subject = "chore(repo): " + "a" * 65
        self.assertEqual(policy.subject_errors(subject, RULES, warnings), [])
        self.assertEqual(len(warnings), 1)
        self.assertTrue(self.errors("chore(repo): " + "a" * 84))

    def test_lowercase_english_imperative_and_no_period(self):
        for description in (
            "Preserve ownership",
            "fixed ownership",
            "fixes ownership",
            "preserve ownership.",
            "\u0441\u043e\u0445\u0440\u0430\u043d\u0438\u0442\u044c ownership",
        ):
            with self.subTest(description=description):
                self.assertTrue(self.errors(f"chore(repo): {description}"))

    def test_imperative_verbs_are_not_rejected_as_inflected_forms(self):
        for verb in ("add", "fix", "update", "change", "implement", "remove"):
            self.assertEqual(self.errors(f"chore(repo): {verb} repository checks"), [])

    def test_required_prose_body(self):
        for kind in RULES["commit"]["body_required"]:
            self.assertTrue(self.errors(f"{kind}(repo): preserve ownership"))
        for kind in ("chore", "build", "ci", "revert"):
            self.assertEqual(self.errors(f"{kind}(repo): preserve ownership"), [])

    def test_prose_limits_and_blank_separator(self):
        self.assertTrue(
            self.errors(MESSAGE + "\nThird paragraph.\n\nFourth paragraph.")
        )
        self.assertTrue(self.errors(MESSAGE + "a" * 81))
        self.assertTrue(self.errors("fix(repo): preserve ownership\n" + BODY))
        self.assertTrue(self.errors(MESSAGE + "Trailing space. \n"))

    def test_prose_stubs_and_placeholders_are_not_useful(self):
        for kind in ("feat", "chore", "ci", "build"):
            for body in (
                "done",
                "TODO: write a useful explanation here",
                "placeholder",
            ):
                self.assertTrue(
                    self.errors(f"{kind}(repo): preserve ownership\n\n{body}")
                )

    def test_bullets_fences_and_unknown_trailers(self):
        for text in (
            "- preserve ownership",
            "1. preserve ownership",
            "```text",
            "~~~text",
            "Acked-by: Someone",
            "Co-authored-by: Someone",
            "Signed-off-by: Someone",
        ):
            with self.subTest(text=text):
                self.assertTrue(self.errors(MESSAGE + "\n" + text))

    def test_whole_message_prohibitions_on_subject_only(self):
        for subject in (
            "chore(repo): add generated by AI code",
            "chore(repo): add code written by chatgpt",
            "chore(repo): record session recap",
            "chore(repo): claim all tests pass",
            "chore(repo): add Co-authored-by: someone",
        ):
            with self.subTest(subject=subject):
                self.assertTrue(self.errors(subject))

    def test_provider_topics_are_not_attribution(self):
        for brand in ("claude", "copilot", "chatgpt", "Claude", "Copilot", "ChatGPT"):
            message = f"fix(provider): handle {brand} response errors\n\nHandle {brand} provider failures without dropping queued requests."
            self.assertEqual(self.errors(message), [])
            for attribution in (
                "written by",
                "authored by",
                "implemented with",
                "assisted by",
                "generated with",
            ):
                self.assertTrue(
                    self.errors(f"chore(repo): add code {attribution} {brand}")
                )

    def test_allowed_reference_trailers(self):
        self.assertEqual(self.errors(MESSAGE + "\nFixes #12\nRefs #34\n"), [])
        self.assertTrue(self.errors(MESSAGE + "\nFixes #0\n"))
        self.assertTrue(self.errors(MESSAGE + "\nRefs #12\nMore prose after trailers."))

    def test_breaking_markers_must_be_synchronized(self):
        breaking = MESSAGE.replace("runtime):", "runtime)!:")
        self.assertTrue(self.errors(breaking))
        self.assertTrue(self.errors(MESSAGE + "\nBREAKING CHANGE: Remove the old API."))
        self.assertTrue(self.errors(breaking + "\nBREAKING CHANGE:"))
        self.assertEqual(
            self.errors(breaking + "\nBREAKING CHANGE: Remove the old API."), []
        )
        self.assertTrue(
            self.errors(
                breaking + "\nBREAKING CHANGE: Remove it.\nBREAKING CHANGE: Again."
            )
        )

    def test_real_merge_context_not_fake_subject(self):
        message = "Merge branch 'master' into ci/repository-policy\n"
        self.assertTrue(self.errors(message))
        self.assertTrue(self.errors(message, (b"parent",)))
        self.assertEqual(self.errors(message, (b"one", b"two")), [])
        self.assertTrue(
            self.errors(message + "\nCo-authored-by: Someone", (b"one", b"two"))
        )
        self.assertTrue(
            self.errors(
                message + "\nBREAKING CHANGE: Remove the API.", (b"one", b"two")
            )
        )

    def test_conventional_merge_requires_empty_body(self):
        parents = (b"one", b"two")
        self.assertEqual(self.errors("fix(runtime): preserve ownership", parents), [])
        self.assertTrue(self.errors(MESSAGE, parents))
        self.assertTrue(self.errors("Merge pull request #1 from owner/branch", parents))

    def test_breaking_pr_merge_requires_empty_body_not_footer(self):
        subject = "fix(runtime)!: remove unchecked cancellation (#123)"
        self.assertEqual(self.errors(subject, (b"one", b"two")), [])
        self.assertTrue(self.errors(subject))
        self.assertTrue(self.errors(subject, (b"one",)))
        self.assertTrue(
            self.errors(
                subject + "\n\nBREAKING CHANGE: Remove the old API.", (b"one", b"two")
            )
        )
        self.assertTrue(
            self.errors(
                "fix(runtime)!: add generated by AI code (#123)", (b"one", b"two")
            )
        )

    def test_github_suffix_exemption_requires_actual_merge(self):
        title = "chore(repo): " + "a" * (95 - len("chore(repo): "))
        self.assertEqual(len(title), 95)
        self.assertEqual(self.errors(title + " (#123)", (b"one", b"two")), [])
        self.assertTrue(self.errors(title + "a (#123)", (b"one", b"two")))
        self.assertTrue(self.errors(title + " (#123)"))
        self.assertTrue(self.errors(title + " (#123)", (b"one",)))
        self.assertTrue(
            self.errors("chore(repo): preserve ownership. (#123)", (b"one", b"two"))
        )
        self.assertTrue(
            self.errors("chore(repo): Preserve ownership (#123)", (b"one", b"two"))
        )

    def test_signature_presence_is_headers_only_and_not_trust(self):
        self.assertFalse(
            policy.signature_present(b"tree abc\n\nchore(repo): add gpgsig header")
        )
        self.assertFalse(
            policy.signature_present(b"tree abc\ngpgsig nonsense\n\nmessage")
        )
        self.assertFalse(
            policy.signature_present(b"tree abc\n\n-----BEGIN SSH SIGNATURE-----\n")
        )
        self.assertFalse(
            policy.signature_present(
                b"tree abc\ngpgsig -----BEGIN SSH SIGNATURE-----\n -----END SSH SIGNATURE-----\n\nmessage"
            )
        )
        # Synthetic armor exercises parsing only; not a signed fixture or trust proof.
        for kind in (b"SSH", b"PGP"):
            raw = (
                b"tree abc\ngpgsig -----BEGIN "
                + kind
                + b" SIGNATURE-----\n payload\n -----END "
                + kind
                + b" SIGNATURE-----\n\nmessage"
            )
            self.assertTrue(policy.signature_present(raw))


class ConfigTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(
            prefix="repo-policy-config-",
            dir="/tmp/opencode" if Path("/tmp/opencode").is_dir() else None,
        )
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)

    def load(self, config):
        # These fixtures use only TOML-compatible JSON scalars and arrays.
        lines = [
            f"{key} = {json.dumps(value)}"
            for key, value in config.items()
            if not isinstance(value, dict)
        ]
        for section, fields in config.items():
            if isinstance(fields, dict):
                lines += [
                    f"[{section}]",
                    *(f"{key} = {json.dumps(value)}" for key, value in fields.items()),
                ]
        (self.root / ".repo-policy.toml").write_text(
            "\n".join(lines) + "\n", encoding="utf-8"
        )
        return policy.load_policy(self.root)

    def test_valid_policy_roundtrip_and_deliberate_scope_expansion(self):
        self.assertEqual(self.load(RULES), RULES)
        config = copy.deepcopy(RULES)
        config["commit"]["scopes"].append("policy")
        self.assertEqual(self.load(config), config)

    def test_unknown_and_missing_sections_and_keys(self):
        config = copy.deepcopy(RULES)
        config["unknown"] = {"enabled": True}
        with self.assertRaisesRegex(policy.PolicyError, "sections.*unknown.*unknown"):
            self.load(config)
        for section in RULES:
            config = copy.deepcopy(RULES)
            del config[section]
            with (
                self.subTest(section=section),
                self.assertRaisesRegex(policy.PolicyError, section),
            ):
                self.load(config)
        for section, fields in RULES.items():
            if not isinstance(fields, dict):
                continue
            config = copy.deepcopy(RULES)
            config[section]["unknown"] = True
            with (
                self.subTest(section=section),
                self.assertRaisesRegex(policy.PolicyError, "unknown"),
            ):
                self.load(config)
            for key in fields:
                config = copy.deepcopy(RULES)
                del config[section][key]
                with (
                    self.subTest(section=section, key=key),
                    self.assertRaisesRegex(policy.PolicyError, key),
                ):
                    self.load(config)

    def test_all_fields_enforce_types_and_integer_positivity(self):
        for section, fields in RULES.items():
            if not isinstance(fields, dict):
                continue
            config = copy.deepcopy(RULES)
            config[section] = []
            with (
                self.subTest(section=section),
                self.assertRaisesRegex(
                    policy.PolicyError, section + " must be a table"
                ),
            ):
                self.load(config)
            for key, value in fields.items():
                wrong = "wrong" if not isinstance(value, str) else 1
                replacements = [wrong]
                if type(value) is int:
                    replacements += [True, 0, -1]
                if type(value) is bool:
                    replacements.append(1)
                for replacement in replacements:
                    config = copy.deepcopy(RULES)
                    config[section][key] = replacement
                    with (
                        self.subTest(section=section, key=key, value=replacement),
                        self.assertRaisesRegex(
                            policy.PolicyError, section + r"\." + key
                        ),
                    ):
                        self.load(config)

    def test_invalid_version_and_toml_have_actionable_errors(self):
        for value in (True, 0, 2, "1", 1.0):
            config = copy.deepcopy(RULES)
            config["version"] = value
            with (
                self.subTest(value=value),
                self.assertRaisesRegex(policy.PolicyError, "version must be integer 1"),
            ):
                self.load(config)
        (self.root / ".repo-policy.toml").write_text("version = [", encoding="utf-8")
        with self.assertRaisesRegex(policy.PolicyError, r"\.repo-policy\.toml:"):
            policy.load_policy(self.root)

    def test_pattern_lists_require_unique_nonempty_strings(self):
        for section, fields in RULES.items():
            if not isinstance(fields, dict):
                continue
            for key, value in fields.items():
                if not isinstance(value, list) or key == "upper_bounds":
                    continue
                for invalid in (
                    [],
                    [""],
                    [" "],
                    ["\0"],
                    [1],
                    [True],
                    [value[0], value[0]],
                ):
                    config = copy.deepcopy(RULES)
                    config[section][key] = invalid
                    with (
                        self.subTest(section=section, key=key, value=invalid),
                        self.assertRaisesRegex(
                            policy.PolicyError, section + r"\." + key
                        ),
                    ):
                        self.load(config)

    def test_scalar_strings_and_all_regex_parameters_are_validated(self):
        for section, fields in RULES.items():
            if not isinstance(fields, dict):
                continue
            for key, value in fields.items():
                if isinstance(value, str):
                    for invalid in ("", " ", "\0"):
                        config = copy.deepcopy(RULES)
                        config[section][key] = invalid
                        with (
                            self.subTest(section=section, key=key),
                            self.assertRaisesRegex(
                                policy.PolicyError, section + r"\." + key
                            ),
                        ):
                            self.load(config)
        for section, key in (
            ("commit", "nonimperative_start"),
            ("commit", "sync_merge"),
            ("commit", "forbidden"),
            ("branch", "pattern"),
            ("pr", "placeholder"),
            ("changelog", "slug_pattern"),
            ("files", "conflict_marker"),
        ):
            config = copy.deepcopy(RULES)
            config[section][key] = ["["] if key == "forbidden" else "["
            with (
                self.subTest(section=section, key=key),
                self.assertRaisesRegex(
                    policy.PolicyError, section + r"\." + key + ".*invalid regex"
                ),
            ):
                self.load(config)
        config = copy.deepcopy(RULES)
        config["changelog"]["slug_pattern"] = "(?i)slug"
        with self.assertRaisesRegex(policy.PolicyError, "slug_pattern.*invalid regex"):
            self.load(config)
        for invalid in ("a{99999999999999999999999}", "(" * 1000 + "a" + ")" * 1000):
            config = copy.deepcopy(RULES)
            config["branch"]["pattern"] = invalid
            with (
                self.subTest(pattern=invalid[:30]),
                self.assertRaisesRegex(
                    policy.PolicyError, "branch.pattern.*invalid regex"
                ),
            ):
                self.load(config)

    def test_size_bounds_labels_and_related_fields(self):
        for key, values in (
            (
                "upper_bounds",
                (
                    [0, 200, 500, 1000],
                    [-1, 200, 500, 1000],
                    [200, 50, 500, 1000],
                    [50, 50, 500, 1000],
                    [True, 200, 500, 1000],
                    ["50", 200, 500, 1000],
                ),
            ),
            ("labels", (["XS", "S"], ["XS", "S", "M", "L", "xl"])),
        ):
            for value in values:
                config = copy.deepcopy(RULES)
                config["size"][key] = value
                with (
                    self.subTest(key=key, value=value),
                    self.assertRaisesRegex(policy.PolicyError, "size\\." + key),
                ):
                    self.load(config)
        for section, key, value in (
            ("pr", "large_labels", ["XXL"]),
            ("commit", "subject_target", 96),
            ("commit", "body_required", ["unknown"]),
            ("commit", "types", ["bad-type"]),
            ("commit", "scopes", ["bad_scope"]),
            ("changelog", "kinds", ["bad.kind"]),
        ):
            config = copy.deepcopy(RULES)
            config[section][key] = value
            with (
                self.subTest(section=section, key=key),
                self.assertRaises(policy.PolicyError),
            ):
                self.load(config)

    def test_paths_are_relative_and_only_changelog_readme_is_exempt(self):
        for section, key, value in (
            ("size", "source", ["/src/**"]),
            ("files", "markdown", ["../*.md"]),
            ("changelog", "directory", "/changelog.d"),
            ("changelog", "directory", "."),
            ("changelog", "directory", "./changelog.d"),
            ("changelog", "directory", "changelog.d/"),
            ("changelog", "directory", "changelog*"),
            ("changelog", "exclude", ["changelog.d/skip.fixed.md"]),
        ):
            config = copy.deepcopy(RULES)
            config[section][key] = value
            with (
                self.subTest(section=section, key=key, value=value),
                self.assertRaisesRegex(policy.PolicyError, r"\.repo-policy\.toml"),
            ):
                self.load(config)


class GitTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(
            prefix="repo-policy-",
            dir="/tmp/opencode" if Path("/tmp/opencode").is_dir() else None,
        )
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.git("init", "-q", "-b", "master")
        self.rules = copy.deepcopy(RULES)

    def git(self, *args):
        result = subprocess.run(
            [
                "git",
                "-c",
                "user.name=Policy Test",
                "-c",
                "user.email=policy@example.invalid",
                "-c",
                "commit.gpgsign=false",
                "-c",
                "core.hooksPath=/dev/null",
                *args,
            ],
            cwd=self.root,
            capture_output=True,
            check=True,
        )
        return result.stdout.decode().strip()

    def write(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text if isinstance(text, bytes) else text.encode())

    def commit(
        self, message="chore(repo): preserve repository policy", allow_empty=False
    ):
        self.git("add", "--all")
        args = ["commit", "-q", "-m", message]
        if allow_empty:
            args.append("--allow-empty")
        self.git(*args)
        return self.git("rev-parse", "HEAD")

    def baseline(self):
        self.write("src/main.rs", "one\ntwo\nthree\nfour\n")
        return self.commit()

    def size(self, base, head="HEAD"):
        return policy.measure_size(
            self.root, self.rules, base, policy.revision(self.root, head)
        )

    def event(self, head):
        return {
            "pull_request": {
                "head": {"sha": head, "ref": "ci/repository-policy"},
                "base": {"ref": "master"},
                "title": "ci(repo): enforce repository review policy",
                "body": "## Summary\nEnforce mechanical repository rules before accepting changes.\n\n## Verification\nRun focused standard-library tests covering Git history and files.\n\n## Change Impact\nImpact: internal\nThis changes contributor checks without altering application behavior.\n",
            }
        }

    def pr(self, base, head, event=None):
        return policy.pr_errors(
            self.root,
            self.rules,
            event or self.event(head),
            base,
            head,
            self.size(base, head),
        )

    def cli(self, *args, policy_text=None):
        self.write(
            ".repo-policy.toml",
            policy_text
            if policy_text is not None
            else (ROOT / ".repo-policy.toml").read_bytes(),
        )
        return subprocess.run(
            [sys.executable, str(ROOT / "scripts/repo_policy.py"), *args],
            cwd=self.root,
            capture_output=True,
            text=True,
        )

    def test_root_range_and_initial_push_all_zero(self):
        root = self.baseline()
        head = self.commit(allow_empty=True)
        self.assertEqual(policy.commit_ids(self.root, None, head), [root, head])
        self.assertEqual(policy.commit_ids(self.root, "0" * 40, head), [root, head])
        self.assertEqual(policy.commit_ids(self.root, root, head), [head])

    def test_missing_or_unsafe_revisions_fail(self):
        self.baseline()
        for value in ("--all", "HEAD~1", "HEAD;touch bad", "f" * 40, "0" * 40):
            with self.subTest(value=value), self.assertRaises(policy.PolicyError):
                policy.revision(self.root, value)
        with self.assertRaises(policy.PolicyError):
            policy.commit_ids(self.root, "f" * 40, policy.revision(self.root, "HEAD"))

    def test_signature_rejection_and_mocked_structural_presence(self):
        head = self.baseline()
        errors, notices = policy.check_commits(self.root, self.rules, None, head)
        self.assertTrue(any("missing SSH/GPG signature" in e for e in errors))
        self.assertIn("presence only", notices[-1])
        with patch.object(policy, "signature_present", return_value=True):
            errors, notices = policy.check_commits(self.root, self.rules, None, head)
        self.assertEqual(errors, [])
        self.assertIn("deferred", notices[-1])
        with self.assertRaises(policy.PolicyError):
            policy.check_commits(self.root, self.rules, None, head, verify=True)

    def test_real_merge_parent_count_via_history(self):
        root = self.baseline()
        self.git("switch", "-q", "-c", "ci/side")
        self.write("side.txt", "side\n")
        self.commit()
        self.git("switch", "-q", "master")
        self.write("main.txt", "main\n")
        self.commit()
        self.git("merge", "--no-ff", "ci/side", "-m", "Merge branch 'ci/side'")
        head = policy.revision(self.root, "HEAD")
        with patch.object(policy, "signature_present", return_value=True):
            self.assertEqual(
                policy.check_commits(self.root, self.rules, root, head)[0], []
            )

    def test_real_breaking_merge_preserves_underlying_commit_checks(self):
        root = self.baseline()
        self.git("switch", "-q", "-c", "ci/breaking")
        self.write("side.txt", "side\n")
        self.commit(
            MESSAGE.replace("runtime):", "runtime)!:")
            + "\nBREAKING CHANGE: Remove the old API."
        )
        self.git("switch", "-q", "master")
        self.write("main.txt", "main\n")
        self.commit()
        title = "fix(runtime)!: remove unchecked cancellation (#123)"
        self.git("merge", "--no-ff", "ci/breaking", "-m", title)
        head = policy.revision(self.root, "HEAD")
        with patch.object(policy, "signature_present", return_value=True):
            self.assertEqual(
                policy.check_commits(self.root, self.rules, root, head)[0], []
            )
        self.git("switch", "-q", "-c", "ci/invalid")
        invalid = self.commit(
            MESSAGE.replace("runtime):", "runtime)!:"), allow_empty=True
        )
        self.git("switch", "-q", "master")
        self.commit(allow_empty=True)
        self.git("merge", "--no-ff", "ci/invalid", "-m", title)
        head = policy.revision(self.root, "HEAD")
        with patch.object(policy, "signature_present", return_value=True):
            errors = policy.check_commits(self.root, self.rules, root, head)[0]
        self.assertEqual(len(errors), 1)
        self.assertIn(invalid[:12], errors[0])
        self.assertIn("synchronized", errors[0])

    def test_size_aggregates_not_sum_of_commits(self):
        base = self.baseline()
        self.write("src/main.rs", "changed\n")
        self.commit()
        self.write("src/main.rs", "one\ntwo\nthree\nfour\n")
        head = self.commit()
        size = self.size(base, head)
        self.assertEqual(size["totals"]["files"], 0)
        self.assertEqual(size["reviewable_churn"], 0)

    def test_updated_base_uses_merge_base(self):
        original = self.baseline()
        self.git("switch", "-q", "-c", "ci/feature")
        self.write("tests/check.py", "feature\n")
        head = self.commit()
        self.git("switch", "-q", "master")
        self.write("docs/base.md", "Updated base without the feature.\n")
        updated = self.commit()
        size = self.size(updated, head)
        self.assertEqual(size["base"], original)
        self.assertEqual(size["totals"]["files"], 1)
        self.assertEqual(size["groups"]["tests"]["files"], 1)
