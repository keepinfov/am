    def test_files_cli_rejects_fragments_and_invalid_policy_without_traceback(self):
        self.baseline()
        self.write(
            "changelog.d/bad.unknown.md",
            "Preserve queued requests when cancellation stops the active attempt.\n",
        )
        result = self.cli("files")
        self.assertEqual(result.returncode, 1)
        self.assertIn("invalid changelog fragment name", result.stderr)
        text = (ROOT / ".repo-policy.toml").read_text(encoding="utf-8")
        for invalid, expected in (
            (text + "\n[unknown]\nenabled = true\n", "unknown"),
            (text.replace("max_length = 48", "max_length = true"), "branch.max_length"),
            (
                text.replace(
                    "slug_pattern = '[a-z0-9]+(?:-[a-z0-9]+)*'", "slug_pattern = '['"
                ),
                "changelog.slug_pattern",
            ),
        ):
            result = self.cli("files", policy_text=invalid)
            self.assertEqual(result.returncode, 1)
            self.assertIn(expected, result.stderr)
            self.assertNotIn("Traceback", result.stderr)


